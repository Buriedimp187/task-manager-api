USERS = User.__table__


def test_users_table_columns_and_nullability():
    columns = USERS.columns

    assert list(columns.keys()) == ["id", "username", "password_hash", "created_at"]
    assert isinstance(columns.id.type, Integer) and columns.id.primary_key
    assert isinstance(columns.id.identity, Identity)
    assert (columns.username.type.length, columns.username.nullable) == (32, False)
    assert (columns.password_hash.type.length, columns.password_hash.nullable) == (255, False)
    assert isinstance(columns.created_at.type, DateTime) and columns.created_at.type.timezone
    assert str(columns.created_at.server_default.arg) == "now()"


def test_usernames_are_unique_case_insensitively_through_a_database_index():
    [index] = [index for index in USERS.indexes if index.name == "uq_users_username_lower"]
    ddl = str(CreateIndex(index).compile(dialect=postgresql.dialect()))

    assert index.unique is True
    assert ddl == "CREATE UNIQUE INDEX uq_users_username_lower ON users (lower(username))"
    # Plain uniqueness on the column would be case-sensitive, so it must not be what is relied on.
    assert not USERS.columns.username.unique
    assert not [c for c in USERS.constraints if type(c).__name__ == "UniqueConstraint"]


def test_users_constraint_names_are_deterministic():
    assert {constraint.name for constraint in USERS.constraints} == {"pk_users", "ck_users_username_format"}


def test_users_ddl():
    ddl = str(CreateTable(USERS).compile(dialect=postgresql.dialect()))

    assert "id INTEGER GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "username VARCHAR(32) NOT NULL" in ddl
    assert "password_hash VARCHAR(255) NOT NULL" in ddl
    assert "CHECK (username ~ '^[A-Za-z0-9_.-]{3,32}$')" in ddl


USERNAME_CANDIDATES = [
    "abc", "ab", "a" * 32, "a" * 33, "A_b-c.d", "bad name", "bad\n", "\nbad", " bad", "bad ", "émile",
    "名前名前", "a/b", "ali@ce", "a\x00b", "", "..-", "___", "1234",
]  # fmt: skip


USERNAME_CHECK = next(c for c in USERS.constraints if c.name == "ck_users_username_format")
# The body of the database pattern, e.g. [A-Za-z0-9_.-]{3,32}; it must match the whole name.
DATABASE_USERNAME_PATTERN = re.search(r"~ '\^(.+)\$'", str(USERNAME_CHECK.sqltext)).group(1)


@pytest.mark.parametrize("candidate", USERNAME_CANDIDATES)
def test_the_api_username_rule_and_the_database_check_accept_the_same_names(candidate):
    accepted_by_database = re.fullmatch(DATABASE_USERNAME_PATTERN, candidate) is not None
    try:
        UserCreate(username=candidate, password="a perfectly fine password")
        accepted_by_api = True
    except ValidationError:
        accepted_by_api = False

    assert accepted_by_api == accepted_by_database, repr(candidate)


def test_user_read_exposes_no_password_material():
    created_at = datetime(2026, 1, 2, 3, 4, 5, tzinfo=UTC)
    user = User(id=3, username="Alice", password_hash="$argon2id$v=19$m=1,t=1,p=1$c2FsdA$aGFzaA", created_at=created_at)

    read = UserRead.model_validate(user)

    assert read.model_dump() == {"id": 3, "username": "Alice", "created_at": created_at}
    assert "password" not in str(UserRead.model_json_schema()).lower()
