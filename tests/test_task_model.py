from datetime import UTC, datetime
from pathlib import Path

import pytest
from pydantic import ValidationError
from sqlalchemy import CheckConstraint, DateTime, Identity, Integer, String
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from app.models import Base, Task
from app.schemas import TaskCreate, TaskRead, TaskStatus

TABLE = Task.__table__
APP_DIR = Path(__file__).resolve().parent.parent / "app"


def test_table_has_the_expected_columns():
    assert TABLE.name == "tasks"
    assert list(TABLE.columns.keys()) == ["id", "title", "description", "status", "created_at"]


def test_column_types_and_nullability():
    columns = TABLE.columns

    assert isinstance(columns.id.type, Integer) and columns.id.primary_key
    assert isinstance(columns.id.identity, Identity)
    assert (columns.title.type.length, columns.title.nullable) == (200, False)
    assert isinstance(columns.title.type, String)
    assert (columns.description.type.length, columns.description.nullable) == (2000, True)
    assert columns.status.nullable is False
    assert isinstance(columns.created_at.type, DateTime) and columns.created_at.type.timezone
    assert columns.created_at.nullable is False


def test_database_side_defaults():
    columns = TABLE.columns

    assert columns.status.server_default.arg == TaskStatus.todo.value
    assert str(columns.created_at.server_default.arg) == "now()"


def test_status_values_match_the_api_enum():
    allowed = [status.value for status in TaskStatus]

    assert TABLE.columns.status.type.enums == allowed
    assert TABLE.columns.status.type.native_enum is False  # VARCHAR + CHECK, not a PostgreSQL enum


def test_constraints_have_deterministic_names():
    names = {constraint.name for constraint in TABLE.constraints}

    assert names == {"pk_tasks", "ck_tasks_title_not_blank", "ck_tasks_task_status"}
    assert all(isinstance(c, CheckConstraint) for c in TABLE.constraints if c.name.startswith("ck_"))


def test_generated_postgresql_ddl():
    ddl = str(CreateTable(TABLE).compile(dialect=postgresql.dialect()))

    assert "id INTEGER GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "title VARCHAR(200) NOT NULL" in ddl
    assert "description VARCHAR(2000)," in ddl
    assert "status VARCHAR(20) DEFAULT 'todo' NOT NULL" in ddl
    assert "created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL" in ddl
    assert "CHECK (char_length(btrim(title)) > 0)" in ddl
    assert "CHECK (status IN ('todo', 'in_progress', 'done'))" in ddl


def test_column_limits_match_the_api_limits():
    title_limit = TABLE.columns.title.type.length
    description_limit = TABLE.columns.description.type.length

    TaskCreate(title="x" * title_limit, description="y" * description_limit)
    with pytest.raises(ValidationError):
        TaskCreate(title="x" * (title_limit + 1))
    with pytest.raises(ValidationError):
        TaskCreate(title="x", description="y" * (description_limit + 1))


def test_task_read_accepts_an_orm_object():
    created_at = datetime(2026, 1, 2, 3, 4, 5, tzinfo=UTC)
    task = Task(
        id=7,
        title="Write tests",
        description=None,
        status=TaskStatus.in_progress,
        created_at=created_at,
    )

    read = TaskRead.model_validate(task)

    assert read.model_dump() == {
        "id": 7,
        "title": "Write tests",
        "description": None,
        "status": TaskStatus.in_progress,
        "created_at": created_at,
    }


def test_task_read_still_accepts_plain_dictionaries():
    data = {
        "id": 1,
        "title": "t",
        "description": "d",
        "status": "done",
        "created_at": "2026-01-02T03:04:05Z",
    }

    assert TaskRead.model_validate(data).status is TaskStatus.done


def test_task_read_rejects_objects_missing_fields():
    with pytest.raises(ValidationError):
        TaskRead.model_validate(Task(id=1, title="only a title"))


def test_metadata_registers_only_the_tasks_table():
    assert list(Base.metadata.tables) == ["tasks"]


def test_application_code_never_creates_tables_itself():
    # Schema changes belong exclusively to Alembic migrations.
    offenders = [
        path.name for path in APP_DIR.rglob("*.py") if "create_all" in path.read_text(encoding="utf-8")
    ]

    assert offenders == []
