@requires_test_database
def test_downgrade_holds_a_lock_that_blocks_concurrent_writers(test_database):
    engine, config = test_database
    command.upgrade(config, "head")
    counted, release = threading.Event(), threading.Event()
    result = {}

    def pause_after_the_count(conn, cursor, statement, parameters, context, executemany):
        # Pauses only the migration's own thread, in the window between its count and its DROP.
        if threading.current_thread().name == "downgrade-thread" and COUNT_STATEMENT in statement:
            counted.set()
            release.wait(timeout=20)

    def run_downgrade():
        try:
            command.downgrade(config, "base")
        except Exception as error:  # reported below, from the main thread
            result["error"] = error

    event.listen(Engine, "after_cursor_execute", pause_after_the_count)
    worker = threading.Thread(target=run_downgrade, name="downgrade-thread")
    try:
        worker.start()
        assert counted.wait(timeout=20), "the downgrade never reached its count"

        with engine.connect() as writer:
            writer.execute(text("SET lock_timeout = '1s'"))
            with pytest.raises(OperationalError) as blocked:
                writer.execute(text("INSERT INTO tasks (title) VALUES ('arrives mid-downgrade')"))
        assert isinstance(blocked.value.orig, psycopg.errors.LockNotAvailable)
    finally:
        release.set()
        worker.join(timeout=30)
        event.remove(Engine, "after_cursor_execute", pause_after_the_count)

    assert "error" not in result
    assert "tasks" not in inspect(engine).get_table_names()


