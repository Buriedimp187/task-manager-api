def load_initial_migration():
    path = PROJECT_ROOT / "alembic" / "versions" / "0001_create_tasks_table.py"
    spec = importlib.util.spec_from_file_location("initial_migration", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


LOCK_STATEMENT = "LOCK TABLE tasks IN ACCESS EXCLUSIVE MODE"


class RecordingOp:
    """Stands in for `alembic.op` so the downgrade's statement order can be checked without a database."""

    def __init__(self, task_count, as_sql=False):
        self.calls = []
        self.task_count = task_count
        self.as_sql = as_sql

    def get_context(self):
        return SimpleNamespace(as_sql=self.as_sql)

    def get_bind(self):
        return self

    def execute(self, statement):
        self.calls.append(str(statement))
        return SimpleNamespace(scalar_one=lambda: self.task_count)

    def drop_table(self, name):
        self.calls.append(f"drop_table:{name}")


def run_downgrade_with(recorder):
    migration = load_initial_migration()
    migration.op = recorder
    migration.downgrade()


def test_downgrade_locks_the_table_before_counting_and_dropping():
    recorder = RecordingOp(task_count=0)

    run_downgrade_with(recorder)

    assert recorder.calls == [LOCK_STATEMENT, COUNT_STATEMENT, "drop_table:tasks"]


def test_downgrade_refuses_a_populated_table_before_dropping_anything():
    recorder = RecordingOp(task_count=2)

    with pytest.raises(RuntimeError, match=r"contains 2 task\(s\)") as error:
        run_downgrade_with(recorder)

    assert recorder.calls == [LOCK_STATEMENT, COUNT_STATEMENT]  # no drop_table call
    assert str(error.value) == (
        "Refusing to drop the tasks table: it contains 2 task(s). "
        "Delete them first if you really want to discard the data."
    )  # the count is reported, never the contents


def test_offline_mode_does_not_lock_or_count_so_generated_sql_is_unprotected():
    recorder = RecordingOp(task_count=99, as_sql=True)

    run_downgrade_with(recorder)  # does not raise although "99 tasks" would be refused online

    assert recorder.calls == ["drop_table:tasks"]


def test_destructive_alembic_calls_only_run_behind_the_safety_checks():
    """Every online upgrade/downgrade in the test suite must sit behind the `test_database` fixture."""
    # Targets an unreachable port on purpose, so it cannot touch any database.
    exempt = {"test_migration_failure_does_not_leak_the_password"}
    offenders = []
    fixture_calls = []
    guard_lines = []

    for path in sorted(Path(__file__).resolve().parent.glob("*.py")):  # test modules and conftest.py
        tree = ast.parse(path.read_text(encoding="utf-8"))
        functions = [node for node in ast.walk(tree) if isinstance(node, ast.FunctionDef)]
        # A nested helper runs under its enclosing test, so it is judged by that test's fixtures.
        nested = {inner for outer in functions for inner in ast.walk(outer) if inner is not outer and inner in functions}

        for function in [function for function in functions if function not in nested]:
            for call in [node for node in ast.walk(function) if isinstance(node, ast.Call)]:
                target = call.func
                if function.name == "test_database" and getattr(target, "id", None) == "refuse_unless_disposable":
                    guard_lines.append(call.lineno)
                is_alembic = (
                    isinstance(target, ast.Attribute)
                    and isinstance(target.value, ast.Name)
                    and target.value.id == "command"
                    and target.attr in {"upgrade", "downgrade"}
                )
                offline = any(
                    keyword.arg == "sql" and getattr(keyword.value, "value", None) is True
                    for keyword in call.keywords
                )
                if not is_alembic or offline:
                    continue
                if function.name == "test_database":
                    fixture_calls.append(call.lineno)
                elif "test_database" not in [arg.arg for arg in function.args.args] and function.name not in exempt:
                    offenders.append(f"{path.name}::{function.name}")

    assert offenders == []

    # Inside the fixture (conftest.py), the refusal check must come before the first upgrade/downgrade.
    assert guard_lines and fixture_calls and max(guard_lines) < min(fixture_calls)


