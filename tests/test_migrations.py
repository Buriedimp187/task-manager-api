def add_user(engine, username="owner"):
    with engine.begin() as connection:
        return connection.execute(
            text("INSERT INTO users (username, password_hash) VALUES (:name, 'not-a-real-hash') RETURNING id"),
            {"name": username},
        ).scalar_one()


def add_task(engine, owner_id, title="a task"):
    with engine.begin() as connection:
        return connection.execute(
            text("INSERT INTO tasks (owner_id, title) VALUES (:owner, :title) RETURNING id"),
            {"owner": owner_id, "title": title},
        ).scalar_one()


def count(engine, table):
    with engine.connect() as connection:
        return connection.execute(text(f"SELECT count(*) FROM {table}")).scalar_one()


def revision(engine):
    with engine.connect() as connection:
        return connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one_or_none()


def test_upgrade_creates_the_expected_schema(test_database):
    engine, config = test_database

    command.upgrade(config, "head")

    inspector = inspect(engine)
    tasks = {column["name"]: column for column in inspector.get_columns("tasks")}
    assert list(tasks) == ["id", "title", "description", "status", "created_at", "owner_id"]
    assert [name for name, column in tasks.items() if not column["nullable"]] == [
        "id",
        "title",
        "status",
        "created_at",
        "owner_id",
    ]
    users = {column["name"]: column for column in inspector.get_columns("users")}
    assert list(users) == ["id", "username", "password_hash", "created_at"]
    assert all(not column["nullable"] for column in users.values())
    assert {c["name"] for c in inspector.get_check_constraints("tasks")} == {
        "ck_tasks_title_not_blank",
        "ck_tasks_task_status",
    }
    assert {c["name"] for c in inspector.get_check_constraints("users")} == {"ck_users_username_format"}
    assert inspector.get_pk_constraint("tasks")["name"] == "pk_tasks"
    [foreign_key] = inspector.get_foreign_keys("tasks")
    assert foreign_key["name"] == "fk_tasks_owner_id_users"
    assert foreign_key["referred_table"] == "users" and foreign_key["options"]["ondelete"] == "CASCADE"
    indexes = {index["name"]: index for index in inspector.get_indexes("tasks")}
    assert indexes["ix_tasks_owner_id_id"]["column_names"] == ["owner_id", "id"]


