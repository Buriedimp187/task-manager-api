def run_downgrade_paused(test_database, target, count_statement, while_paused):
    """Run `alembic downgrade target` in a thread, paused between its row count and its DROP, and call
    `while_paused()` meanwhile. Returns the error the downgrade itself raised, if any.

    It takes the `test_database` fixture value, so it cannot be used without the safety checks."""
    _, config = test_database
    counted, release = threading.Event(), threading.Event()
    result = {}

    def pause_after_the_count(conn, cursor, statement, parameters, context, executemany):
        # Pauses only the migration's own thread, in the window between its count and its DROP.
        if threading.current_thread().name == "downgrade-thread" and count_statement in statement:
            counted.set()
            release.wait(timeout=20)

    def run_downgrade():
        try:
            command.downgrade(config, target)
        except Exception as error:  # reported to the caller, from the main thread
            result["error"] = error

    event.listen(Engine, "after_cursor_execute", pause_after_the_count)
    worker = threading.Thread(target=run_downgrade, name="downgrade-thread")
    try:
        worker.start()
        assert counted.wait(timeout=20), "the downgrade never reached its count"
        while_paused()
    finally:
        release.set()
        worker.join(timeout=30)
        event.remove(Engine, "after_cursor_execute", pause_after_the_count)
    return result.get("error")


def test_0001_downgrade_holds_a_lock_that_blocks_concurrent_writers(test_database):
    engine, config = test_database
    command.upgrade(config, "0001")
    outcome = {}

    def try_to_write():
        with engine.connect() as writer:
            writer.execute(text("SET lock_timeout = '1s'"))
            with pytest.raises(OperationalError) as blocked:
                writer.execute(text("INSERT INTO tasks (title) VALUES ('arrives mid-downgrade')"))
            outcome["blocked"] = blocked.value

    assert run_downgrade_paused(test_database, "base", COUNT_STATEMENT, try_to_write) is None
    assert isinstance(outcome["blocked"].orig, psycopg.errors.LockNotAvailable)
    assert "tasks" not in inspect(engine).get_table_names()


