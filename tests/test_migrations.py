def load_migration(filename):
    path = PROJECT_ROOT / "alembic" / "versions" / filename
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class RecordingOp:
    """Stands in for `alembic.op` so a migration's statement order can be checked without a database."""

    def __init__(self, task_count=0, user_count=0, as_sql=False):
        self.calls = []
        self.counts = {"tasks": task_count, "users": user_count}
        self.as_sql = as_sql

    def get_context(self):
        return SimpleNamespace(as_sql=self.as_sql)

    def get_bind(self):
        return self

    def execute(self, statement):
        sql = str(statement)
        self.calls.append(sql)
        table = sql.rsplit("FROM ", 1)[-1] if "count(*)" in sql else None
        return SimpleNamespace(scalar_one=lambda: self.counts[table])

    def f(self, name):
        return name

    def __getattr__(self, name):
        def record(*args, **kwargs):
            self.calls.append(f"{name}:{args[0] if args else ''}")

        return record


def run(migration, direction, recorder):
    migration.op = recorder
    getattr(migration, direction)()


